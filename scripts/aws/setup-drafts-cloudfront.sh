#!/usr/bin/env bash
# One-time: CloudFront (HTTPS) in front of drafts S3 bucket via OAC.
# S3 website endpoints cannot serve a trusted SSL cert — use CloudFront instead.
set -euo pipefail

AWS_PROFILE="${AWS_PROFILE:-Peak}"
AWS_REGION="${AWS_REGION:-ap-south-1}"
BUCKET="${S3_DRAFTS_BUCKET:-peaklife-website-drafts-ap-south-1}"
ACCOUNT_ID="${AWS_ACCOUNT_ID:-660878112326}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

echo "Setting up CloudFront for s3://${BUCKET} (profile ${AWS_PROFILE})…"

if ! aws s3api head-bucket --bucket "$BUCKET" --profile "$AWS_PROFILE" 2>/dev/null; then
  echo "Bucket missing. Run setup-drafts-bucket.sh first."
  exit 1
fi

# Reuse existing drafts OAC if present
OAC_ID=$(aws cloudfront list-origin-access-controls --profile "$AWS_PROFILE" \
  --query "OriginAccessControlList.Items[?Name=='peaklife-website-drafts-oac'].Id | [0]" \
  --output text)
if [[ -z "$OAC_ID" || "$OAC_ID" == "None" ]]; then
  echo "Creating Origin Access Control…"
  OAC_ID=$(aws cloudfront create-origin-access-control \
    --origin-access-control-config "file://${SCRIPT_DIR}/oac-drafts.json" \
    --profile "$AWS_PROFILE" \
    --query 'OriginAccessControl.Id' \
    --output text)
  echo "  OAC: ${OAC_ID}"
else
  echo "Reusing OAC: ${OAC_ID}"
fi

# Reuse existing drafts distribution if comment matches
DIST_ID=$(aws cloudfront list-distributions --profile "$AWS_PROFILE" \
  --query "DistributionList.Items[?Comment=='Peak website drafts / staging (S3 ap-south-1)'].Id | [0]" \
  --output text)

if [[ -z "$DIST_ID" || "$DIST_ID" == "None" ]]; then
  CALLER_REF="peaklife-website-drafts-$(date +%Y%m%d%H%M%S)"
  TMP_CONFIG="$(mktemp)"
  sed \
    -e "s/REPLACE_CALLER_REF/${CALLER_REF}/" \
    -e "s/REPLACE_OAC_ID/${OAC_ID}/" \
    "${SCRIPT_DIR}/cloudfront-distribution-drafts.json" > "$TMP_CONFIG"

  echo "Creating CloudFront distribution…"
  DIST_ID=$(aws cloudfront create-distribution \
    --distribution-config "file://${TMP_CONFIG}" \
    --profile "$AWS_PROFILE" \
    --query 'Distribution.Id' \
    --output text)
  rm -f "$TMP_CONFIG"

  DIST_DOMAIN=$(aws cloudfront get-distribution --id "$DIST_ID" --profile "$AWS_PROFILE" \
    --query 'Distribution.DomainName' --output text)
  echo "  Distribution: ${DIST_ID}"
  echo "  Domain: ${DIST_DOMAIN}"
else
  DIST_DOMAIN=$(aws cloudfront get-distribution --id "$DIST_ID" --profile "$AWS_PROFILE" \
    --query 'Distribution.DomainName' --output text)
  echo "Reusing distribution: ${DIST_ID} (${DIST_DOMAIN})"
fi

POLICY=$(cat <<EOF
{
  "Version": "2012-10-17",
  "Statement": [
    {
      "Sid": "AllowCloudFrontServicePrincipalRead",
      "Effect": "Allow",
      "Principal": {
        "Service": "cloudfront.amazonaws.com"
      },
      "Action": "s3:GetObject",
      "Resource": "arn:aws:s3:::${BUCKET}/*",
      "Condition": {
        "StringEquals": {
          "AWS:SourceArn": "arn:aws:cloudfront::${ACCOUNT_ID}:distribution/${DIST_ID}"
        }
      }
    }
  ]
}
EOF
)

echo "Applying OAC bucket policy (CloudFront-only read)…"
aws s3api put-bucket-policy \
  --bucket "$BUCKET" \
  --policy "$POLICY" \
  --profile "$AWS_PROFILE"

echo "Blocking public access (traffic goes through CloudFront HTTPS)…"
aws s3api put-public-access-block \
  --bucket "$BUCKET" \
  --public-access-block-configuration \
    "BlockPublicAcls=true,IgnorePublicAcls=true,BlockPublicPolicy=true,RestrictPublicBuckets=true" \
  --profile "$AWS_PROFILE"

# Persist IDs next to other aws scripts for humans / CI docs
cat > "${SCRIPT_DIR}/drafts-cloudfront.env" <<EOF
# Generated by setup-drafts-cloudfront.sh — safe to commit (IDs only, no secrets)
S3_DRAFTS_BUCKET=${BUCKET}
CLOUDFRONT_DRAFTS_OAC_ID=${OAC_ID}
CLOUDFRONT_DRAFTS_DISTRIBUTION_ID=${DIST_ID}
CLOUDFRONT_DRAFTS_DOMAIN=${DIST_DOMAIN}
CLOUDFRONT_DRAFTS_URL=https://${DIST_DOMAIN}
EOF

echo ""
echo "Done. Staging HTTPS URL:"
echo "  https://${DIST_DOMAIN}"
echo ""
echo "Set GitHub environment \`staging\` variable CLOUDFRONT_DISTRIBUTION_ID=${DIST_ID}"
echo "Deploy workflow will sync S3 + invalidate CloudFront."
echo "IDs written to scripts/aws/drafts-cloudfront.env"
echo ""
echo "Note: new distributions take ~5–15 minutes to reach Deployed status."
